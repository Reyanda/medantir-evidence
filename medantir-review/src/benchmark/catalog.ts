export function getBenchmarkCase(id: string): BenchmarkCase {
  const benchmark = benchmarkCatalog.find((candidate) => candidate.id === id);
  if (!benchmark) throw new Error(`Unknown benchmark case '${id}'`);
  return benchmark;
}

export function benchmarkCasesForReviewType(reviewType: BenchmarkCase['reviewType']): BenchmarkCase[] {
  return benchmarkCatalog.filter((benchmark) => benchmark.reviewType === reviewType);
}
